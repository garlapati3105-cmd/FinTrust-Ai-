from __future__ import annotations

import os
import re
import tempfile
from contextlib import contextmanager
from pathlib import Path
from typing import Generator

# Configurable limits with safe defaults
MAX_UPLOAD_SIZE_BYTES = int(os.getenv("MAX_UPLOAD_SIZE_MB", "10")) * 1024 * 1024
MAX_PDF_PAGES = int(os.getenv("MAX_PDF_PAGES", "10"))

# Known file signatures (magic bytes)
SIGNATURE_PDF = b"%PDF-"
SIGNATURE_PNG = b"\x89PNG\r\n\x1a\n"
SIGNATURE_JPEG = b"\xff\xd8\xff"

SUPPORTED_MIME_TYPES = {
    "application/pdf": "pdf",
    "image/png": "png",
    "image/jpeg": "jpeg",
    "image/jpg": "jpeg",
}

# Suspicious instruction patterns for prompt-injection detection (heuristic scanner)
SUSPICIOUS_PATTERNS = [
    re.compile(r"ignore\s+(all\s+)?(previous|prior|above)\s+instructions?", re.IGNORECASE),
    re.compile(r"disregard\s+(all\s+)?(previous|prior|above)\s+instructions?", re.IGNORECASE),
    re.compile(r"system\s+prompt", re.IGNORECASE),
    re.compile(r"admin(istrator)?\s+override", re.IGNORECASE),
    re.compile(r"developer\s+mode", re.IGNORECASE),
    re.compile(r"you\s+are\s+now\s+in\s+([a-z_]+)\s+mode", re.IGNORECASE),
    re.compile(r"approve\s+(this\s+)?invoice\s+(automatically|directly|without\s+checks?)", re.IGNORECASE),
    re.compile(r"always\s+approve(\s+this\s+invoice)?", re.IGNORECASE),
    re.compile(r"bypass\s+(verification|checks?|validation|security)", re.IGNORECASE),
    re.compile(r"override\s+(the\s+)?(vendor|account|bank|decision|rule|po|amount)", re.IGNORECASE),
    re.compile(r"reveal\s+(your\s+|the\s+)?(system\s+prompt|secret|key|password|instructions?)", re.IGNORECASE),
    re.compile(r"<\|im_start\|>", re.IGNORECASE),
    re.compile(r"\[INST\]", re.IGNORECASE),
]


def detect_file_type(content: bytes, filename: str = "") -> str:
    """
    Validates actual file signature (magic bytes) and returns normalized type:
    'pdf', 'png', or 'jpeg'.
    Raises ValueError if unsupported or mismatched.
    """
    if not content:
        raise ValueError("Uploaded file is completely empty.")

    if len(content) > MAX_UPLOAD_SIZE_BYTES:
        raise ValueError(
            f"File size ({len(content) / (1024 * 1024):.2f} MB) exceeds maximum allowed limit "
            f"of {MAX_UPLOAD_SIZE_BYTES / (1024 * 1024):.0f} MB."
        )

    # Magic byte inspection
    if content.startswith(SIGNATURE_PDF):
        return "pdf"
    elif content.startswith(SIGNATURE_PNG):
        return "png"
    elif content.startswith(SIGNATURE_JPEG):
        return "jpeg"

    # If magic bytes don't match, reject regardless of filename extension
    ext = Path(filename).suffix.lower() if filename else "unknown"
    raise ValueError(
        f"Unsupported file format or invalid file signature (extension: {ext}). "
        f"Only valid PDF, PNG, and JPEG documents are permitted."
    )


@contextmanager
def safe_temporary_file(content: bytes, suffix: str = ".bin") -> Generator[Path, None, None]:
    """
    Creates a temporary file in a secure temp directory with an autogenerated,
    randomized name (never using user-supplied filenames).
    Guarantees deletion in finally block.
    """
    fd, temp_path_str = tempfile.mkstemp(suffix=suffix)
    temp_path = Path(temp_path_str)
    try:
        with os.fdopen(fd, "wb") as f:
            f.write(content)
        yield temp_path
    finally:
        try:
            if temp_path.exists():
                temp_path.unlink()
        except OSError:
            pass


def scan_for_suspicious_content(text: str) -> list[str]:
    """
    Scans extracted document text for prompt-injection phrases or directive keywords.
    Returns a list of human-readable warnings if suspicious text is found.
    """
    warnings: list[str] = []
    if not text:
        return warnings

    for pattern in SUSPICIOUS_PATTERNS:
        match = pattern.search(text)
        if match:
            warnings.append(
                f"Suspicious instruction pattern identified: '{match.group(0)}'. "
                f"Document content may contain prompt-injection attempts."
            )
    return warnings
